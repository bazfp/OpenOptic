#!/usr/bin/env python3
"""Build shading_8100.js, the OpticFilm 8100's software flat-field reference, from a usbspy capture.

    python3 tools/build_shading_8100.py captures/capture_05_clean.log shading_8100.js

The chip applies no shading to the 8100's data (no shading tables are uploaded in the captures), so the host has to.
The free trial software's calibration reads, found in the capture by their geometry, are:
  * a lamp-off 10-line probe with the black-level offset (register 0x3B) at its final value 0x01 -> per-channel dark level
  * a 566-line lamp-on pass over a clear area at 7200 dpi (DPISET 1200, STRPIXEL 24, ENDPIXEL 10472) -> per-pixel white
The white reference is stored per sensor pixel on the 7200 dpi grid (STRPIXEL/ENDPIXEL are in those units); a scan at
a lower resolution samples every (1200/DPISET)-th pixel of it. Needs numpy. Writes data only, no image."""
import base64, hashlib, importlib.util, json, pathlib, sys
import numpy as np

here = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(here))
spec = importlib.util.spec_from_file_location('bcp', here / 'build_capture_profiles.py')
sys.argv = [sys.argv[0], '--none'] + sys.argv[1:]
bcp = importlib.util.module_from_spec(spec); spec.loader.exec_module(bcp)
cap, out = sys.argv[2:4]

_, raw = bcp.decode(cap)
regs = {}; cur = None; probes = []
for e in raw:
    if e['kind'] == 'ctl' and e['bmr'] == 0x40 and e['wv'] == 0x83 and len(e['out']) > 1:
        d = e['out']
        for a, v in zip(d[::2], d[1::2]):
            regs[a] = v
            if a == 0x0F and v == 1 and regs.get(1, 0) & 1:
                u16 = lambda r: (regs[r] << 8) | regs[r + 1]
                cur = dict(lines=(regs[0x25] << 16) | (regs[0x26] << 8) | regs[0x27], str=u16(0x30), end=u16(0x32), dpiset=u16(0x2C),
                           lper=u16(0x38), r3=regs.get(3), r3b=regs.get(0x3B), data=b''); probes.append(cur)
    elif e['kind'] == 'bin' and cur is not None:
        cur['data'] += e['data']

def pixels(p): return (p['end'] - p['str']) * p['dpiset'] // 1200

white = next(p for p in probes if p['lines'] == 566 and p['dpiset'] == 1200)
dark = [p for p in probes if p['lines'] == 10 and p['dpiset'] == 1200 and p['r3'] == 0x8F and p['r3b'] == 0x01][-1]
n = pixels(white)
assert len(white['data']) >= white['lines'] * n * 6, 'white pass incomplete in the capture'
w = np.frombuffer(white['data'][:white['lines'] * n * 6], dtype='<u2').reshape(white['lines'], n, 3)
col = np.median(w[8:-8], axis=0).round().astype('<u2')                 # per sensor pixel, per channel
nd = pixels(dark)
d = np.frombuffer(dark['data'][:dark['lines'] * nd * 6], dtype='<u2').reshape(dark['lines'], nd, 3)
darkmean = [round(float(v), 1) for v in d.reshape(-1, 3).mean(0)]
def noise_stats(a):
    # as CaptureRuntime.noiseStats (the 7600i's multi-exposure noise model): per column the variance across lines, averaged over the central 80 % of columns (every 3rd)
    P = a.shape[1]; x0, x1 = P // 10, P - P // 10; c = a[:, x0:x1:3, :].astype(np.float64)
    return {'mean': [round(float(v), 1) for v in c.mean(axis=0).mean(axis=0)], 'tvar': [round(float(v), 1) for v in c.var(axis=0).mean(axis=0)]}
ref = {'source': pathlib.Path(cap).name, 'sha256': hashlib.sha256(pathlib.Path(cap).read_bytes()).hexdigest(),
       'str': white['str'], 'end': white['end'], 'pixels': n, 'lper': white['lper'], 'dark': darkmean, 'darkLper': dark['lper'],
       'noise': {'dark': noise_stats(d), 'white': noise_stats(w[8:-8])},   # read noise and photon-transfer gain for the multi-exposure merge
       'saturated': int((col >= 65000).any(axis=1).sum()), 'white': base64.b64encode(col.tobytes()).decode()}
pathlib.Path(out).write_text('// Generated by tools/build_shading_8100.py from a the free trial software usbspy capture: per-pixel white reference and dark level, no image data.\n'
                             'globalThis.SHADING_8100=' + json.dumps(ref, separators=(',', ':')) + ';\n')
print(out, pathlib.Path(out).stat().st_size, 'bytes:', n, 'pixels, dark', darkmean, 'saturated columns', ref['saturated'])
